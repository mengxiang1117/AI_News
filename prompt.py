# 新闻领域分析 prompt
NEWS_CATEGORY_ANALYSIS = """
针对同花顺财经新闻的特性，这是一个非常关键的补充。同花顺的新闻高度个股驱动，且经常只出现股票代码或公司简称，如果不结合外部知识将“股票/公司”映射到其“主营业务”和“行业属性”，领域分类就会浮于表面（例如把大量新闻都归为“公司”或“股票”，失去了分类意义）。

以下是结合你的需求深度优化后的提示词：

```markdown
# 任务：新闻领域分析

## 角色
你是一名资深的专业财经新闻分析师，精通A股及资本市场，熟知各家上市公司的主营业务和所属行业。你擅长从高度个股驱动的新闻文本中，透过股票代码/公司名称看清其背后的行业实质，并严格按照给定分类体系进行归类。

## 输入信息

### 可选领域列表
{categories}

### 新闻标题
{title}

### 新闻内容
{content}

## 分析规则

**严格闭域**：必须且只能从【可选领域列表】中选择领域，绝不可自行臆造或同义词替换列表之外的领域。
**穿透个股看行业（核心规则）**：
 - 同花顺新闻中常包含大量股票代码（如：300750）、公司简称（如：宁德时代）或泛称（如：某头部电池厂）。
 - **你必须调用自身知识库，识别这些股票/公司的主营业务**，并提取其所属的宏观领域。
 - 绝不能仅仅因为新闻提到了某家公司，就生硬地输出"公司"或"股票"领域，而应输出该公司代表的业务领域（如：宁德时代 -> "新能源"/"锂电池"）。
**核心事实优先**：判断依据应是新闻的“核心事实与影响”，而非偶然提及的实体。如果新闻主要讲“新能源补贴政策”，哪怕文中列举了多家新能源公司，核心领域也是"政策"与"新能源"。
**多领域提取**：当新闻涉及多个交叉领域时，请提取所有核心相关领域，但避免过度泛化。
**无关处理**：如果新闻内容与可选领域列表中的任何领域均无实质性关联，则输出空数组。

## 输出要求

- 仅输出一个标准的 JSON 数组，不要包含任何 Markdown 标记（如 ```json ）、注释、解释或额外文字。
- 每个领域名称用双引号包裹，且必须与可选领域列表中的名称完全一致（包括大小写、空格等）。
- 领域之间保持互斥，不要有重复项。
- 如果无相关领域，输出空数组 `[]`。

## 示例
假设可选领域列表为：["新能源", "汽车", "政策", "半导体", "消费电子", "医药"]

**输入1**：
新闻标题：宁德时代(300750)披露中报，净利润同比增长超预期
新闻内容：...
**输出**：["新能源"]

**输入2**：
新闻标题：中芯国际(688981)与长电科技达成战略合作，加速Chiplet封装产能扩充
新闻内容：...
**输出**：["半导体"]

**输入3**：
新闻标题：发改委发布2024年新能源汽车补贴退坡政策，比亚迪(002594)回应影响有限
新闻内容：...
**输出**：["新能源", "汽车", "政策"]

**输入4**：
新闻标题：某当红娱乐明星八卦曝光
新闻内容：...
**输出**：[]
"""


def get_news_category_prompt(categories: list, title: str, content: str) -> str:
    """
    获取新闻领域分析 prompt

    Args:
        categories: 可选领域列表
        title: 新闻标题
        content: 新闻内容

    Returns:
        格式化后的 prompt
    """
    # 格式化领域列表，每行一个领域
    formatted_categories = "\n".join([f"- {cat}" for cat in categories])

    return NEWS_CATEGORY_ANALYSIS.format(
        categories=formatted_categories,
        title=title,
        content=content
    )
